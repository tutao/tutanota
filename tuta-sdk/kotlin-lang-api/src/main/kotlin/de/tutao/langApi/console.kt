package de.tutao.langApi

class console {
	companion object {
		fun log(vararg items: Any) {
			println(items)
		}

		fun warn(vararg items: Any) {
			println(items)
		}

		fun debug(vararg items: Any) {
			println(items)
		}

		fun error(vararg items: Any) {
			println(items)
		}

		fun trace(vararg items: Any) {
			println(items)
		}
	}
}
